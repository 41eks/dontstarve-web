import { readFile, writeFile } from 'node:fs/promises';
import { isDeepStrictEqual, parseArgs } from 'node:util';

import { recordPrefab } from './record.mjs';

const { values } = parseArgs({
  args: process.argv.slice(2).filter(arg => arg !== '--'),
  options: {
    'source-root': { type: 'string', default: process.env.DST_LUA_ROOT },
    check: { type: 'boolean' },
    'callback-source': { type: 'boolean' },
  },
});

function readWorkLeft(recordings) {
  const values = recordings
    .filter(recording => recording.scenario.master)
    .map(recording => {
      const calls = recording.operations.filter(
        operation =>
          operation.kind === 'call' &&
          operation.entity === recording.entity &&
          operation.target === 'components.workable' &&
          operation.name === 'SetWorkLeft',
      );
      const workLeft = calls[0]?.args[0];
      if (
        calls.length !== 1 ||
        calls[0].args.length !== 1 ||
        !calls[0].literalArgument ||
        !Number.isSafeInteger(workLeft) ||
        workLeft <= 0
      ) {
        throw new Error(`Expected one positive integer literal for SetWorkLeft in ${recording.scenario.name}`);
      }
      return workLeft;
    });
  if (new Set(values).size !== 1) {
    throw new Error('SetWorkLeft differs across MasterSim scenarios');
  }
  return values[0];
}

function* differences(previous, current, path) {
  if (isDeepStrictEqual(previous, current)) {
    return;
  }
  if (
    previous !== null &&
    typeof previous === 'object' &&
    current !== null &&
    typeof current === 'object' &&
    Array.isArray(previous) === Array.isArray(current)
  ) {
    for (const key of new Set([...Object.keys(previous), ...Object.keys(current)])) {
      const operation = current[key];
      const member = Array.isArray(current)
        ? `[${key}]${operation?.target && operation?.name ? ` (${operation.target}.${operation.name})` : ''}`
        : `.${key}`;
      yield* differences(previous[key], current[key], path + member);
    }
    return;
  }
  yield `${path}: ${JSON.stringify(previous) ?? '(missing)'} -> ${JSON.stringify(current) ?? '(missing)'}`;
}

async function updateFile(file, output, check) {
  if (!check) {
    await writeFile(file, output);
    return;
  }
  const previous = await readFile(file, 'utf8').catch(error => {
    if (error.code === 'ENOENT') {
      return '';
    }
    throw error;
  });
  if (previous === output) {
    return;
  }

  console.error(`${file.pathname} is out of date`);
  if (file.pathname.endsWith('.json') && previous) {
    let count = 0;
    for (const change of differences(JSON.parse(previous), JSON.parse(output), 'pighead')) {
      console.error(`  ${change}`);
      if (++count === 10) {
        break;
      }
    }
  }
  process.exitCode = 1;
}

async function main() {
  if (!values['source-root']) {
    throw new Error('Pass --source-root <DST scripts directory> or set DST_LUA_ROOT');
  }
  if (values.check && values['callback-source']) {
    throw new Error('--callback-source prints a report and cannot be used with --check');
  }
  const snapshot = await recordPrefab(values['source-root'], 'prefabs/stickheads.lua', 'pighead', {
    includeCallbackSource: values['callback-source'],
  });
  const json = JSON.stringify(snapshot, null, 2) + '\n';
  if (values['callback-source']) {
    process.stdout.write(json);
    return;
  }

  const schema = `// Generated by pnpm extract:lua from ${snapshot.file}. See tools/lua-extractor/snapshots/pighead.json.
export const PIGHEAD_WORK_LEFT = ${readWorkLeft(snapshot.recordings)} as const;
`;
  await updateFile(new URL('snapshots/pighead.json', import.meta.url), json, values.check);
  await updateFile(
    new URL('../../packages/prefab/src/generated/pighead.schema.ts', import.meta.url),
    schema,
    values.check,
  );
  if (!process.exitCode) {
    const counts = snapshot.recordings.map(({ scenario, operations }) => `${scenario.name} ${operations.length}`);
    console.log(`${values.check ? 'Verified' : 'Generated'} pighead (${counts.join(', ')}).`);
  }
}

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
